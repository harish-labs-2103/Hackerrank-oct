"""Evaluation harness.

    python code/evaluation/main.py              # samples (LLM if available, cached) + custom cases
    python code/evaluation/main.py --no-llm     # deterministic only
    python code/evaluation/main.py --write-report

Scores the 32 public samples against dataset/sample_output.csv, runs the team-authored custom
cases under code/evaluation/custom_cases/, measures LLM influence (deterministic vs LLM-assisted
diff on the full request set) and optionally rewrites evaluation_report.md's metrics section.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from davestigator.app import open_session, requests_for  # noqa: E402
from davestigator.config import Settings, load_settings  # noqa: E402
from davestigator.scoring import load_rows, score  # noqa: E402


def run(session, reqs):
    out = {}
    for q in reqs:
        r = session.investigator.investigate(q)
        out[q.case_id] = (r.deletion_status, [s.to_json() for s in r.steps])
    return out


def custom_cases(use_llm: bool):
    results = []
    for d in sorted((HERE / "custom_cases").glob("*/dataset")):
        s = Settings()
        s.dataset.root = str(d)
        sess = open_session(s, use_llm=use_llm)
        pred = run(sess, requests_for(sess))
        gold = load_rows(d.parent / "expected_output.csv")
        sc = score(gold, pred)
        results.append((d.parent.name, (d.parent / "README.md").read_text().split("\n", 2)[-1].strip(), sc))
    return results


def fmt_pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def metrics_md(sc, title: str) -> str:
    d = sc.as_dict()
    fa = d["field_accuracy"]
    lines = [f"### {title}", "", "| Metric | Value |", "|---|---|",
             f"| Cases | {d['cases']} |",
             f"| Case-level deletion-status accuracy | **{fmt_pct(d['status_accuracy'])}** |",
             f"| Exact row match (status + full steps_json) | {fmt_pct(d['exact_row_accuracy'])} |",
             f"| Step precision (operation+system+resource) | {fmt_pct(d['step_precision'])} |",
             f"| Step recall | {fmt_pct(d['step_recall'])} |",
             f"| Step F1 | **{fmt_pct(d['step_f1'])}** |",
             f"| Evidence-ID accuracy on matched steps | {fmt_pct(d['step_evidence_accuracy'])} |",
             f"| Sequence accuracy (identical ordered step list) | {fmt_pct(d['sequence_accuracy'])} |",
             "", "Field-level accuracy (positional, against gold step i):", "",
             "| " + " | ".join(fa) + " |", "|" + "---|" * len(fa), "| " + " | ".join(fmt_pct(v) for v in fa.values()) + " |",
             "", "Status confusion (gold -> predicted): " + ", ".join(f"`{k}`: {v}" for k, v in d["confusion"].items()), ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-llm", action="store_true")
    ap.add_argument("--write-report", action="store_true", help="Rewrite the generated section of evaluation_report.md")
    ap.add_argument("--influence", action="store_true", help="Also diff deterministic vs LLM-assisted on all 518 requests")
    args = ap.parse_args()
    settings, _ = load_settings()
    use_llm = not args.no_llm

    sess = open_session(settings, use_llm=use_llm)
    gold = load_rows(sess.ds.root / "sample_output.csv")
    pred = run(sess, requests_for(sess, sample=True))
    sc = score(gold, pred)
    print(json.dumps(sc.as_dict(), indent=1))
    for f in sc.failures:
        print(f"  {f['case_id']}: {f['gold_status']}->{f['pred_status']} missing={len(f['missing'])} extra={len(f['extra'])} evid_diff={len(f['evidence_diff'])}")

    customs = custom_cases(use_llm)
    for name, _, c in customs:
        d = c.as_dict()
        print(f"custom {name}: status {fmt_pct(d['status_accuracy'])} exact {fmt_pct(d['exact_row_accuracy'])} F1 {fmt_pct(d['step_f1'])}")

    influence = None
    if args.influence:
        det = open_session(settings, use_llm=False)
        reqs = requests_for(det)
        a, b = run(det, reqs), run(sess, reqs)
        influence = sorted(cid for cid in a if a[cid] != b[cid])
        print(f"LLM influence: {len(influence)} of {len(reqs)} cases differ: {influence}")

    if args.write_report:
        rep = HERE / "evaluation_report.md"
        text = rep.read_text(encoding="utf-8") if rep.exists() else ""
        start, end = "<!-- BEGIN GENERATED METRICS -->", "<!-- END GENERATED METRICS -->"
        gen = [start, "", f"Generated by `python code/evaluation/main.py --write-report{' --influence' if args.influence else ''}"
               f"{' --no-llm' if args.no_llm else ''}` (AI assistance: {sess.ai_status}).", "",
               metrics_md(sc, "Public samples (32 cases, dataset/sample_output.csv)"),
               "#### Sample cases not matched exactly", "",
               "| Case | Gold | Pred | Missing steps | Extra steps | Evidence differences |", "|---|---|---|---|---|---|"]
        for f in sc.failures:
            miss = "<br>".join(f"{op} {r}" for op, _, r in f["missing"]) or "-"
            extra = "<br>".join(f"{op} {r}" for op, _, r in f["extra"]) or "-"
            ev = "<br>".join(f"{k[2]}: {p} vs {g}" for k, p, g in f["evidence_diff"]) or "-"
            gen.append(f"| {f['case_id']} | {f['gold_status']} | {f['pred_status']} | {miss} | {extra} | {ev} |")
        gen += ["", "### Team-authored custom cases", "", "| Case | Scenario | Status correct | Exact row | Step F1 |", "|---|---|---|---|---|"]
        for name, doc, c in customs:
            d = c.as_dict()
            gen.append(f"| `{name}` | {doc} | {fmt_pct(d['status_accuracy'])} | {fmt_pct(d['exact_row_accuracy'])} | {fmt_pct(d['step_f1'])} |")
        if influence is not None:
            gen += ["", "### LLM influence", "", f"{len(influence)} of 518 evaluation cases change between `--no-llm` and the "
                    f"LLM-assisted run" + (f": {', '.join(influence)}." if influence else ".")]
        gen += ["", end]
        block = "\n".join(gen)
        if start in text and end in text:
            text = text[:text.index(start)] + block + text[text.index(end) + len(end):]
        else:
            text = text + "\n" + block + "\n"
        rep.write_text(text, encoding="utf-8")
        print(f"wrote {rep}")


if __name__ == "__main__":
    main()
